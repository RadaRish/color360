echo "   ❌ УСТРАНЕНО: Повторные попытки установки позиции камеры (до 8 раз!)"
echo "   ❌ УСТРАНЕНО: Конфликт между дефолтным видом и предыдущей позицией"
echo "   ❌ УСТРАНЕНО: Резкие скачки при переходе между сценами"
echo ""
echo "✅ Что добавлено:"
echo "   🎯 Стабильное управление позицией камеры без повторных попыток"
echo "   🕐 Единое отключение look-controls на 500мс для установки позиции"
echo "   📍 Детальное логирование процесса установки дефолтного вида"
echo "   🚀 Плавные переходы между сценами без резких скачков"
echo ""
echo "📊 Ожидаемое поведение:"
echo "   🎬 Переход на сцену → плавная установка дефолтного вида → стабильная камера"
