#!/bin/bash

echo "🎥 Исправление резких скачков камеры при переключении сцен..."

cd /var/www/color360

# 1. Загружаем исправления камеры
echo "1️⃣ Загрузка исправлений управления камерой..."
git pull --ff-only origin main

# 2. Перезапускаем с исправлениями
echo "2️⃣ Перезапуск с исправлением управления камерой..."
systemctl restart color360-app

# 3. Проверяем статус
echo "3️⃣ Проверка статуса после исправления..."
sleep 3

if systemctl is-active --quiet color360-app; then
    echo "✅ Приложение запущено"
else
    echo "❌ Проблема с запуском"
    systemctl status color360-app --no-pager
    exit 1
fi

# 4. Проверка базовой функциональности
echo "4️⃣ Проверка функциональности..."
HEALTH_STATUS=$(curl -s -o /dev/null -w "%{http_code}" http://localhost:3000/ 2>/dev/null || echo "000")
if [ "$HEALTH_STATUS" = "200" ]; then
    echo "✅ Приложение отвечает"
else
    echo "⚠️ Приложение код: $HEALTH_STATUS"
fi

echo ""
echo "🎥 ИСПРАВЛЕНЫ РЕЗКИЕ СКАЧКИ КАМЕРЫ!"
echo ""
echo "🐛 Что было исправлено:"
