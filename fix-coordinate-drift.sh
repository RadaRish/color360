#!/bin/bash

echo "🔧 Исправление критических проблем координат и камеры..."

cd /var/www/color360

# 1. Загружаем критическое исправление
echo "1️⃣ Загрузка критического исправления координат..."
git pull --ff-only origin main

# 2. Перезапускаем с новым исправлением
echo "2️⃣ Перезапуск с исправлением дрифта координат..."
systemctl restart color360-app

# 3. Проверяем статус
echo "3️⃣ Проверка статуса после исправления..."
sleep 3

if systemctl is-active --quiet color360-app; then
    echo "✅ Приложение запущено"
else
    echo "❌ Проблема с запуском"
    systemctl status color360-app --no-pager
    exit 1
fi

# 4. Тест базовой функциональности
echo "4️⃣ Проверка базовой функциональности..."
HEALTH_STATUS=$(curl -s -o /dev/null -w "%{http_code}" http://localhost:3000/ 2>/dev/null || echo "000")
if [ "$HEALTH_STATUS" = "200" ]; then
    echo "✅ Основное приложение отвечает"
else
    echo "⚠️ Основное приложение код: $HEALTH_STATUS"
fi

# 5. Проверка LaMa сервиса
echo "5️⃣ Проверка LaMa AI..."
LAMA_STATUS=$(curl -s -o /dev/null -w "%{http_code}" http://localhost:5002/health 2>/dev/null || echo "000")
if [ "$LAMA_STATUS" = "200" ]; then
    echo "✅ LaMa AI отвечает"
else
    echo "⚠️ LaMa AI код: $LAMA_STATUS - попытка перезапуска..."
    systemctl restart color360-lama
    sleep 3
    systemctl is-active color360-lama
fi

# 6. Очистка временных файлов
echo "6️⃣ Очистка временных файлов..."
if [ -d "/var/www/color360/temp" ]; then
    find /var/www/color360/temp -name "temp_*" -mtime +1 -delete 2>/dev/null
    echo "Очищены файлы старше 1 дня"
fi

echo ""
echo "🎯 КРИТИЧЕСКИЕ ИСПРАВЛЕНИЯ ПРИМЕНЕНЫ!"
echo ""
echo "🔧 Координатный дрифт УСТРАНЕН:"
echo "   ❌ УСТРАНЕН: Накопительный дрифт координат при множественных операциях"
echo "   ❌ УСТРАНЕН: Смещение UV координат от (0.41, 0.47) до (0.27, 0.48)"
echo "   ✅ ДОБАВЛЕН: Сброс камеры в (0,0,0) перед каждым маппингом координат"
echo "   ✅ ДОБАВЛЕН: Восстановление исходной ориентации камеры после операции"
echo "   ✅ ДОБАВЛЕН: Детальное логирование позиции камеры для диагностики"
echo ""
echo "🎥 Резкие скачки камеры УСТРАНЕНЫ:"
echo "   ❌ УСТРАНЕНО: Множественные включения/отключения look-controls"
echo "   ❌ УСТРАНЕНО: Повторные попытки установки позиции камеры (до 8 раз!)"
echo "   ❌ УСТРАНЕНО: Конфликт между дефолтным видом и предыдущей позицией"
echo "   ✅ ДОБАВЛЕНО: Стабильное управление камерой при переключении сцен"
echo ""
echo ""
echo "📊 Ожидаемые результаты:"
echo "   🎯 Координаты: UV центра экрана стабильны при множественных операциях"
echo "   � Камера: Плавные переходы между сценами БЕЗ резких скачков"
echo "   � Дефолтный вид: Устанавливается ОДИН раз и остается стабильным"
echo ""
echo "🧪 Для проверки - следите за логом:"  
echo "   📍 'сохранили исходную ориентацию камеры: x:..., y:..., z:...'"
echo "   🔄 'сброшена камера в (0,0,0) для стабильного маппинга'"
echo "   ↩️ 'восстановлена исходная ориентация камеры'"
echo "   📍 центр экрана должен показывать одинаковые UV координаты"